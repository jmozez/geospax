/** A plugin's own icon: each default domain plugin has a distinct one (d-agriculture …), so no two
 *  domains look alike; other plugins use their first tool's icon. */
export function pluginIcon(p: { id: string; tools: { icon?: string }[] }): string {
  const own = `d-${p.id.replace(/^geospax-/, '')}`;
  if (ICONS[own]) return own;
  if (p.id === 'gsx') return 'puzzle';
  return p.tools[0]?.icon ?? 'puzzle';
}

export function icon(name: string, size = 20): string {
  const d = ICONS[name] ?? ICONS.check;
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" aria-hidden="true"><path d="${d}" fill="currentColor"/></svg>`;
}

